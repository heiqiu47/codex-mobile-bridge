/* Execute against the synthetic API fixture; never against a user's gateway. */
window.checkCodexEntries = async function checkCodexEntries() {
  const assert=(value,message)=>{if(!value)throw Error(message);};
  const until=async(fn)=>{for(let i=0;i<100;i++){if(fn())return;await new Promise(resolve=>setTimeout(resolve,40));}throw Error('UI fixture timed out');};
  const wsl='wsl:'+'a'.repeat(32),sid='12345678-1234-4234-9234-123456789012';
  await until(()=>clientNavigation.clients.length===3);
  assert(!document.getElementById('codex-entries'),'old entry controls removed');
  clientNavigation.openManager();
  const scan=[...clientNavigation.manager.dialog.querySelectorAll('button')].find(button=>button.textContent==='扫描 WSL 应用');
  assert(scan,'WSL scan belongs to application manager');await scan.onclick();
  let row=clientNavigation.manager.list.querySelector('[data-client-id="'+wsl+'"]');
  assert(row?.textContent.includes('WSL Codex'),'WSL appears as an independent application');
  assert(row.querySelector('[role=switch]').getAttribute('aria-checked')==='false','discovered app starts disabled');
  await row.querySelector('[role=switch]').onclick();
  row=clientNavigation.manager.list.querySelector('[data-client-id="'+wsl+'"]');
  assert(row.querySelector('[role=switch]').getAttribute('aria-checked')==='true','common application enable switch');
  [...row.querySelectorAll('button')].find(button=>button.textContent==='查看聊天').click();
  await until(()=>document.querySelector('#sessions .session')?.dataset.host===wsl);
  assert(clientNavigation.provider===wsl,'WSL is the selected application');
  assert(!document.querySelector('#sessions .session[data-host=local]'),'Windows conversations excluded');
  assert(document.getElementById('new-chat').hidden,'no desktop create action in WSL');
  await openChat(sid,wsl);await until(()=>state?.model==='group/auto-gpt-6-1-sol');
  await document.getElementById('model-button').onclick();
  const select=document.getElementById('model-select'),models=[...select.options].filter(option=>option.value!=='__custom__');
  assert(models.length===3&&models.every(option=>option.textContent.trim()),'every model has a visible label');
  assert(select.value==='group/auto-gpt-6-1-sol','Magpie group ID is preserved');
  assert([...document.getElementById('effort-select').options].some(option=>option.value==='high'),'native reasoning efforts remain selectable');
  assert(document.documentElement.scrollWidth<=innerWidth,'narrow viewport fits');
  document.getElementById('model-dialog').close();document.getElementById('message').value='WSL draft fixture';
  await clientNavigation.choose('codex');await until(()=>document.querySelector('#sessions .session')?.dataset.host==='local');
  assert(!document.getElementById('new-chat').hidden,'desktop create action restored');
  await clientNavigation.choose(wsl);await until(()=>document.querySelector('#sessions .session')?.dataset.host===wsl);
  await openChat(sid,wsl);assert(document.getElementById('message').value==='WSL draft fixture','WSL draft survives app switching');
  clientNavigation.openManager();await clientNavigation.toggle(wsl,false);
  assert(clientNavigation.provider==='codex','disabled WSL falls back to enabled desktop app');
  assert(!document.querySelector('.client-disable-dialog'),'WSL never offers an unsupported native exit');
  return {passed:16,modelLabels:models.map(option=>option.textContent),application:'WSL Codex',viewport:innerWidth};
};
